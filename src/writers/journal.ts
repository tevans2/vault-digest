/** Insert task lines at the end of a `## Tasks` / `## Actions` style section of any note. */
export function appendToSection(text: string, heading: RegExp, lines: string[]): { text: string; added: number } | null {
  const all = text.split("\n");
  const h = all.findIndex((l) => heading.test(l));
  if (h < 0) return null;
  let fenced = false;
  let end = all.length;
  for (let i = h + 1; i < all.length; i++) {
    if (FENCE.test(all[i])) fenced = !fenced;
    if (fenced) continue;
    if (/^#{1,6}\s/.test(all[i]) || all[i].trim() === "---" || BOUNDARY_RE.test(all[i])) {
      end = i;
      break;
    }
  }
  const fresh = lines.filter((l) => !all.slice(h + 1, end).includes(l));
  if (!fresh.length) return { text, added: 0 };
  let last = end - 1;
  while (last > h && all[last].trim() === "") last--;
  all.splice(last + 1, 0, ...(last === h ? [""] : []), ...fresh);
  return { text: all.join("\n"), added: fresh.length };
}
